namespace Calorator.Database.Enums;

/// <summary>
/// Уровень физической активности (коэффициенты активности для формулы Миффлина — Сан-Жеора).
/// </summary>
public enum ActivityLevel
{
    /// <summary>
    /// Сидячий образ жизни / минимальная активность (коэффициент 1.2)
    /// </summary>
    Sedentary = 1,

    /// <summary>
    /// Легкая физическая активность (тренировки 1-3 раза в неделю, коэффициент 1.375)
    /// </summary>
    Light = 2,

    /// <summary>
    /// Средняя активность (тренировки 3-5 раз в неделю, коэффициент 1.55)
    /// </summary>
    Moderate = 3,

    /// <summary>
    /// Высокая активность (тяжелые тренировки 6-7 раз в неделю, коэффициент 1.725)
    /// </summary>
    High = 4,

    /// <summary>
    /// Экстремальная активность (тяжелая работа / тренировки 2 раза в день, коэффициент 1.9)
    /// </summary>
    VeryHigh = 5
}
